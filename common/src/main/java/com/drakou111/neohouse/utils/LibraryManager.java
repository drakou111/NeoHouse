package com.drakou111.neohouse.utils;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.HashSet;
import java.util.List;
import java.util.Set;

public class LibraryManager {

    private static final String RESOURCE_BASE = "/assets/neohouse/library/";
    private static final String SHIPPED_VERSIONS = "shipped_versions.txt";

    /**
     * Extracts the built-in library (.nh files) into the scripts folder. A file that already exists
     * is replaced only when it is an unmodified copy of a version NeoHouse shipped before (see
     * {@code shipped_versions.txt}), so library updates reach existing installs while files a user
     * edited are never touched.
     *
     * To add a new default file: drop a .nh file (or subdirectory of .nh files) into
     * common/src/main/resources/assets/neohouse/library/ and add its hash to shipped_versions.txt
     * (the build tells you the hash). index.txt is generated by the generateLibraryIndex Gradle task.
     */
    public static void init(Path scriptsDir) {
        Set<String> shipped = readShippedVersions();
        for (String name : listLibraryFiles()) {
            Path dest = scriptsDir.resolve(name);
            try {
                byte[] bundled = readResource(name);
                if (bundled == null) continue;
                if (Files.exists(dest)) {
                    String existing = fingerprint(Files.readAllBytes(dest));
                    if (existing.equals(fingerprint(bundled)) || !shipped.contains(existing + " " + name)) continue;
                }
                Files.createDirectories(dest.getParent());
                Files.write(dest, bundled);
            } catch (IOException e) {
                MessageUtils.warningToChat("Could not install library file " + name + ": " + e.getMessage());
            }
        }
    }

    /** SHA-256 of the text with carriage returns removed, so line-ending conversions don't matter. */
    static String fingerprint(byte[] content) {
        String normalized = new String(content, StandardCharsets.UTF_8).replace("\r", "");
        try {
            byte[] digest = MessageDigest.getInstance("SHA-256").digest(normalized.getBytes(StandardCharsets.UTF_8));
            return HexFormat.of().formatHex(digest);
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException("SHA-256 is unavailable", e);
        }
    }

    /** Lines of {@code <sha256> <library path>}; '#' starts a comment. */
    private static Set<String> readShippedVersions() {
        Set<String> versions = new HashSet<>();
        for (String line : readLines(SHIPPED_VERSIONS)) {
            if (!line.startsWith("#")) versions.add(line);
        }
        return versions;
    }

    private static List<String> listLibraryFiles() {
        return readLines("index.txt");
    }

    private static List<String> readLines(String resource) {
        List<String> lines = new ArrayList<>();
        try {
            byte[] content = readResource(resource);
            if (content == null) return lines;
            for (String line : new String(content, StandardCharsets.UTF_8).split("\n")) {
                String trimmed = line.trim();
                if (!trimmed.isEmpty()) lines.add(trimmed);
            }
        } catch (IOException e) {
            MessageUtils.warningToChat("Could not read built-in library list: " + e.getMessage());
        }
        return lines;
    }

    private static byte[] readResource(String name) throws IOException {
        try (InputStream in = LibraryManager.class.getResourceAsStream(RESOURCE_BASE + name)) {
            return in == null ? null : in.readAllBytes();
        }
    }
}
