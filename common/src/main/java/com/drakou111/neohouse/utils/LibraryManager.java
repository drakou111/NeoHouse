package com.drakou111.neohouse.utils;

import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.List;

public class LibraryManager {

    private static final String RESOURCE_BASE = "/assets/neohouse/library/";

    /**
     * Extracts all .nh files from the built-in library into the scripts folder.
     * Skips files that already exist. Call this once, guarded by the caller's marker.
     *
     * To add a new default file: just drop a .nh file (or subdirectory of .nh files)
     * into common/src/main/resources/assets/neohouse/library/ — no code changes needed.
     * Subdirectory structure is preserved in neohouse-scripts/ on extraction.
     * index.txt is auto-generated by the generateLibraryIndex Gradle task at build time.
     */
    public static void init(Path scriptsDir) {
        for (String name : listLibraryFiles()) {
            Path dest = scriptsDir.resolve(name);
            if (Files.exists(dest)) continue;
            try {
                Files.createDirectories(dest.getParent());
                try (InputStream in = LibraryManager.class.getResourceAsStream(RESOURCE_BASE + name)) {
                    if (in != null) Files.copy(in, dest, StandardCopyOption.REPLACE_EXISTING);
                }
            } catch (IOException ignored) {}
        }
    }

    private static List<String> listLibraryFiles() {
        List<String> names = new ArrayList<>();
        try (InputStream is = LibraryManager.class.getResourceAsStream(RESOURCE_BASE + "index.txt")) {
            if (is == null) return names;
            String content = new String(is.readAllBytes(), StandardCharsets.UTF_8).trim();
            for (String line : content.split("\n")) {
                String name = line.trim();
                if (!name.isEmpty()) names.add(name);
            }
        } catch (IOException ignored) {}
        return names;
    }
}
