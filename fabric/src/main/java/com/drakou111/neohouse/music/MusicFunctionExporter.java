package com.drakou111.neohouse.music;

import com.drakou111.neohouse.compiler.ast.main_statements.FunctionNode;
import com.drakou111.neohouse.compiler.visitors.CompilerNames;
import com.drakou111.neohouse.constants.AddAction;
import com.drakou111.neohouse.constants.Sound;

import java.util.ArrayList;
import java.util.EnumMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Optional;
import java.util.TreeMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

public final class MusicFunctionExporter {

    private static final int MAX_PAUSE = 6000;
    private static final String INDENT = "    ";
    private static final Pattern STOP_VARIABLE = Pattern.compile("(?:p|g|t\\[[a-zA-Z_][a-zA-Z0-9_]*])\\.([a-zA-Z_][a-zA-Z0-9_]*)");

    private MusicFunctionExporter() {}

    private record Event(String soundName, double volume, double pitch) {}

    /** One Housing action of the song, with the kind that counts toward Housing's per-list limits. */
    private record Action(String code, AddAction kind) {}

    /**
     * The song as a script. Without a stop variable the actions are listed flat and the compiler splits
     * them to fit Housing's limits. With one, every chunk of actions is put in
     * {@code if (<check>) { ... } else { return; }}, each as full as Housing allows, so the song can be
     * cut off between any two chunks. A song needing more than one function's 25 conditionals is
     * continued by the compiler in its own helper functions (name_s$0, ...), guards included.
     *
     * @throws IllegalArgumentException when the project's stop variable isn't a valid variable
     */
    public static String toScript(MusicProject project, String functionName) {
        List<Action> actions = songActions(project);
        String stopVariable = project.stopVariable == null ? "" : project.stopVariable.strip();
        Optional<String> problem = stopVariableProblem(stopVariable);
        if (problem.isPresent()) throw new IllegalArgumentException(problem.get());

        StringBuilder sb = new StringBuilder();
        sb.append("// Generated by NeoHouse from \"").append(project.name).append("\"\n");
        sb.append("// ").append(project.totalNotes()).append(" notes, ")
          .append(project.lengthTicks()).append(" ticks (")
          .append(String.format(Locale.ROOT, "%.2f", project.lengthTicks() / (double) MusicProject.TICKS_PER_SECOND))
          .append("s)\n");

        if (stopVariable.isEmpty()) {
            sb.append("function ").append(functionName).append("() {\n");
            for (Action action : actions) sb.append(INDENT).append(action.code()).append('\n');
            sb.append("}\n");
            return sb.toString();
        }

        sb.append("// Stops when ").append(stopVariable).append(project.stopVariableInverted ? " isn't 1" : " is 1")
          .append(" (checked before each block of notes).\n");
        sb.append("long ").append(stopVariable).append(";\n\n");
        String condition = guardCondition(stopVariable, project.stopVariableInverted);
        sb.append("function ").append(functionName).append("() {\n");
        int next = 0;
        while (next < actions.size()) next = appendGuardedBlock(sb, actions, next, condition);
        sb.append("}\n");
        return sb.toString();
    }

    /** Why {@code stopVariable} can't be used, or empty when it can (a blank one means "no stop variable"). */
    public static Optional<String> stopVariableProblem(String stopVariable) {
        String trimmed = stopVariable.strip();
        if (trimmed.isEmpty()) return Optional.empty();

        Matcher matcher = STOP_VARIABLE.matcher(trimmed);
        if (!matcher.matches())
            return Optional.of("Stop variable '%s' should look like p.stop, g.stop or t[team].stop.".formatted(trimmed));
        if (matcher.group(1).length() > CompilerNames.MAX_VARIABLE_NAME)
            return Optional.of("Stop variable name '%s' is longer than %d characters."
                    .formatted(matcher.group(1), CompilerNames.MAX_VARIABLE_NAME));
        return Optional.empty();
    }

    /** The condition under which the song keeps playing. An unset variable reads as 0 through the fallback. */
    private static String guardCondition(String stopVariable, boolean inverted) {
        return stopVariable + "?0 " + (inverted ? "==" : "!=") + " 1";
    }

    private static List<Action> songActions(MusicProject project) {
        TreeMap<Integer, List<Event>> byTick = new TreeMap<>();
        for (MusicTrack track : project.tracks) {
            if (track.muted) continue;
            for (MusicNote note : track.notes) {
                Sound sound = track.soundFor(note);
                double vol   = clamp01to2(track.volumeFor(note));
                double pitch = clamp01to2(track.pitchFor(note));
                byTick.computeIfAbsent(Math.max(0, note.tick), k -> new ArrayList<>())
                      .add(new Event(sound.name(), vol, pitch));
            }
        }

        List<Action> actions = new ArrayList<>();
        int cursor = 0;
        for (Map.Entry<Integer, List<Event>> entry : byTick.entrySet()) {
            int tick = entry.getKey();
            if (tick > cursor) {
                addPauses(actions, tick - cursor);
                cursor = tick;
            }
            for (Event ev : entry.getValue()) {
                actions.add(new Action("playSound(\"" + ev.soundName() + "\", " + num(ev.volume()) + ", "
                        + num(ev.pitch()) + ", INVOKER);", AddAction.PLAY_SOUND));
            }
        }
        return actions;
    }

    private static void addPauses(List<Action> actions, int ticks) {
        while (ticks > 0) {
            int chunk = Math.min(ticks, MAX_PAUSE);
            actions.add(new Action("pause(" + chunk + ");", AddAction.PAUSE));
            ticks -= chunk;
        }
    }

    /** Writes one guarded conditional starting at {@code from} and returns the index of the first action left out. */
    private static int appendGuardedBlock(StringBuilder sb, List<Action> actions, int from, String condition) {
        Map<AddAction, Integer> counts = new EnumMap<>(AddAction.class);
        sb.append(INDENT).append("if (").append(condition).append(") {\n");
        int i = from;
        while (i < actions.size()) {
            Action action = actions.get(i);
            int count = counts.getOrDefault(action.kind(), 0);
            if (count >= action.kind().maxCount) break;
            counts.put(action.kind(), count + 1);
            sb.append(INDENT).append(INDENT).append(action.code()).append('\n');
            i++;
        }
        sb.append(INDENT).append("} else {\n");
        sb.append(INDENT).append(INDENT).append("return;\n");
        sb.append(INDENT).append("}\n");
        return i;
    }

    private static double clamp01to2(double v) {
        return Math.max(0.0, Math.min(2.0, v));
    }

    private static String num(double v) {
        String s = String.format(Locale.ROOT, "%.4f", v);
        int dot = s.indexOf('.');
        int end = s.length();
        while (end > dot + 2 && s.charAt(end - 1) == '0') end--;
        return s.substring(0, end);
    }

    public static String sanitizeFunctionName(String raw) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < raw.length(); i++) {
            char c = raw.charAt(i);
            if (c >= 'A' && c <= 'Z' || c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '_') {
                sb.append(c);
            } else if (c == ' ' || c == '-') {
                sb.append('_');
            }
        }
        String s = sb.toString();
        if (s.isEmpty()) s = "music";
        if (Character.isDigit(s.charAt(0))) s = "_" + s;
        return s.length() > FunctionNode.MAX_NAME_LENGTH ? s.substring(0, FunctionNode.MAX_NAME_LENGTH) : s;
    }
}
