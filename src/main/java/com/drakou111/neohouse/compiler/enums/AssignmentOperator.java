package com.drakou111.neohouse.compiler.enums;

public enum AssignmentOperator {
    ASSIGN,                          // =
    ADD_ASSIGN,                      // +=
    SUB_ASSIGN,                      // -=
    MUL_ASSIGN,                      // *=
    DIV_ASSIGN,                      // /=
    BITWISE_OR_ASSIGN,               // |=
    BITWISE_AND_ASSIGN,              // &=
    BITWISE_XOR_ASSIGN,              // ^=
    LEFT_SHIFT_ASSIGN,               // <<=
    RIGHT_SHIFT_ASSIGN,              // >>=
    UNSIGNED_RIGHT_SHIFT_ASSIGN,     // >>>=
}
